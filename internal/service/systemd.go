func (s *Systemd) Inspect(ctx context.Context, reference Reference) (Observation, error) {
	target := s.resolve(reference)
	observation := Observation{ProcessState: ProcessUnknown, Platform: map[string]any{"unit": target.UnitName}}
	artifact, err := os.ReadFile(target.Path)
	if err == nil {
		observation.Installed = true
		observation.Artifact = artifact
	} else if !errors.Is(err, os.ErrNotExist) {
		return observation, err
	}
	enabledOutput, enabledErr := s.run(ctx, "is-enabled", target.UnitName)
	enabledText := strings.TrimSpace(string(enabledOutput))
	observation.AutoStart = enabledText == "enabled"
	if enabledErr != nil && !missingService(enabledOutput) && enabledText != "disabled" {
		return observation, enabledErr
	}
	showOutput, showErr := s.run(ctx, "show", target.UnitName, "--property=LoadState", "--property=ActiveState", "--property=SubState", "--property=Result", "--property=TriggeredBy", "--property=DropInPaths", "--property=MainPID", "--property=NRestarts", "--property=ActiveEnterTimestamp", "--no-pager")
	if showErr != nil {
		if missingService(showOutput) && !observation.Installed {
			observation.ProcessState = ProcessInactive
			return observation, nil
		}
		return observation, showErr
	}
	properties := parseProperties(showOutput)
	observation.Platform["loadState"] = properties["LoadState"]
	observation.Platform["activeState"] = properties["ActiveState"]
	observation.Platform["subState"] = properties["SubState"]
	observation.Platform["result"] = properties["Result"]
	observation.Platform["triggeredBy"] = properties["TriggeredBy"]
	observation.Platform["dropInPaths"] = properties["DropInPaths"]
	observation.Platform["mainPID"] = properties["MainPID"]
	observation.Platform["restarts"] = properties["NRestarts"]
	observation.Platform["activeEnterTimestamp"] = properties["ActiveEnterTimestamp"]
	observation.ProcessState = systemdProcessState(properties["ActiveState"])
	return observation, nil
}

func (s *Systemd) Logs(ctx context.Context, reference Reference, lines int, follow bool, streams Streams) error {
	args := []string{"--user", "-u", s.resolve(reference).UnitName, "-n", strconv.Itoa(lines), "--no-pager"}
	if follow {
		args = append(args, "--follow")
	}
	_, err := s.runner.Run(ctx, "journalctl", args, streams)
	return err
}

func (s *Systemd) Discover(ctx context.Context) ([]Candidate, error) {
	entries, err := os.ReadDir(s.unitDir)
	if errors.Is(err, os.ErrNotExist) {
		return []Candidate{}, nil
	}
	if err != nil {
		return nil, err
	}
	result := make([]Candidate, 0)
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".service") {
			continue
		}
		path := filepath.Join(s.unitDir, entry.Name())
		raw, readErr := os.ReadFile(path)
		if readErr != nil {
			continue
		}
		embedded := embeddedPlanFromText(string(raw), "# "+embeddedPlanPrefix)
		value, decodeErr := parseSystemdExecutionPlan(raw)
		if decodeErr != nil {
			continue
		}
		if embedded != "" {
			embeddedValue, embeddedErr := decodeEmbeddedPlan(embedded)
			if embeddedErr != nil {
				continue
			}
			value, decodeErr = mergeEmbeddedPlan(value, embeddedValue)
		}
		if decodeErr != nil {
			continue
		}
		connection := strings.TrimSuffix(strings.TrimPrefix(entry.Name(), "tunlite-"), ".service")
		reference := Reference{Connection: connection, Adapter: s.Name(), UnitName: entry.Name(), ArtifactPath: path}
		observation, inspectErr := s.Inspect(ctx, reference)
		if inspectErr != nil {
			continue
		}
		if triggeredBy, _ := observation.Platform["triggeredBy"].(string); strings.TrimSpace(triggeredBy) != "" {
			continue
		}
		if dropIns, _ := observation.Platform["dropInPaths"].(string); strings.TrimSpace(dropIns) != "" && strings.TrimSpace(dropIns) != "[]" {
			continue
		}
		result = append(result, Candidate{Reference: reference, Plan: value, Observation: observation})
	}
	return result, nil
}

func parseSystemdExecutionPlan(raw []byte) (plan.ExecutionPlan, error) {
	properties := make(map[string][]string)
	unitProperties := make(map[string][]string)
	installProperties := make(map[string][]string)
	section := ""
	for _, rawLine := range strings.Split(string(raw), "\n") {
		line := strings.TrimSpace(rawLine)
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = strings.TrimSuffix(strings.TrimPrefix(line, "["), "]")
			if section != "Unit" && section != "Service" && section != "Install" {
				return plan.ExecutionPlan{}, fmt.Errorf("systemd section %s cannot be managed losslessly", section)
			}
			continue
		}
		key, value, found := strings.Cut(line, "=")
		key = strings.TrimSpace(key)
		if found && section == "Service" {
			properties[key] = append(properties[key], value)
		} else if found && section == "Unit" {
			unitProperties[key] = append(unitProperties[key], value)
		} else if found && section == "Install" {
			installProperties[key] = append(installProperties[key], value)
		} else if found {
			return plan.ExecutionPlan{}, errors.New("systemd directive appears outside a supported section")
		}
	}
	if len(installProperties) != 1 || len(installProperties["WantedBy"]) != 1 || strings.TrimSpace(installProperties["WantedBy"][0]) != "default.target" {
		return plan.ExecutionPlan{}, errors.New("systemd service must be enableable through WantedBy=default.target")
	}
	for key, values := range unitProperties {
		switch key {
		case "Description":
			continue
		case "Wants", "After":
			for _, value := range values {
				if strings.TrimSpace(value) != "network-online.target" {
					return plan.ExecutionPlan{}, fmt.Errorf("systemd %s dependency cannot map to a standard Tunlite mode", key)
				}
			}
		default:
			return plan.ExecutionPlan{}, fmt.Errorf("systemd unit key %s cannot be managed losslessly", key)
		}
	}
	if len(properties["ExecStart"]) != 1 || len(properties["ExecStartPre"]) > 0 || len(properties["ExecStartPost"]) > 0 {
		return plan.ExecutionPlan{}, errors.New("systemd service must have exactly one ExecStart and no lifecycle wrappers")
	}
	allowed := map[string]bool{
		"Type": true, "ExecStart": true, "Restart": true, "RestartSec": true,
		"TimeoutStopSec": true, "KillMode": true,
	}
	for key := range properties {
		if !allowed[key] {
			return plan.ExecutionPlan{}, fmt.Errorf("systemd service key %s cannot be managed losslessly", key)
		}
	}
	if values := properties["Type"]; len(values) > 1 || (len(values) == 1 && strings.TrimSpace(values[0]) != "simple") {
		return plan.ExecutionPlan{}, errors.New("systemd service must use Type=simple")
	}
	restartDelay, err := parseSystemdSeconds(properties["RestartSec"], 10, true)
	if err != nil {
		return plan.ExecutionPlan{}, fmt.Errorf("systemd service restart delay: %w", err)
	}
	stopTimeout, err := parseSystemdSeconds(properties["TimeoutStopSec"], 5, false)
	if err != nil {
		return plan.ExecutionPlan{}, fmt.Errorf("systemd service stop timeout: %w", err)
	}
	if values := properties["KillMode"]; len(values) > 1 || (len(values) == 1 && strings.TrimSpace(values[0]) != "control-group") {
		return plan.ExecutionPlan{}, errors.New("systemd service must use KillMode=control-group")
	}
	arguments, err := splitSystemdCommand(properties["ExecStart"][0])
	if err != nil || len(arguments) == 0 {
		return plan.ExecutionPlan{}, errors.New("systemd ExecStart is not safely representable as argv")
	}
	restart := ""
	if len(properties["Restart"]) == 1 {
		restart = strings.TrimSpace(properties["Restart"][0])
	}
	if restart != "always" {
		return plan.ExecutionPlan{}, errors.New("systemd service does not guarantee keep-up recovery")
	}
	value := plan.ExecutionPlan{
		Mode:      plan.ModeDirect,
		Exec:      plan.Exec{Program: arguments[0], Args: arguments[1:], Environment: map[string]string{}},
		Lifecycle: plan.Lifecycle{Restart: restart, RestartDelaySeconds: restartDelay, StopTimeoutSeconds: stopTimeout},
		Endpoints: []plan.Endpoint{}, HealthChecks: []plan.HealthCheck{}, Redactions: []plan.Redaction{},
	}
	if err := plan.Validate(value); err != nil {
		return plan.ExecutionPlan{}, err
	}
	return value, nil
}

func parseSystemdSeconds(values []string, fallback int, allowZero bool) (int, error) {
	if len(values) == 0 {
		return fallback, nil
	}
	if len(values) != 1 {
		return 0, errors.New("must appear exactly once")
	}
	raw := strings.TrimSpace(values[0])
	raw = strings.TrimSuffix(raw, "s")
	value, err := strconv.Atoi(raw)
	if err != nil || value < 0 || (!allowZero && value == 0) {
		return 0, errors.New("must be a valid number of seconds")
	}
	return value, nil
}

func splitSystemdCommand(command string) ([]string, error) {
	var result []string
	for index := 0; index < len(command); {
		for index < len(command) && (command[index] == ' ' || command[index] == '\t') {
			index++
		}
		if index >= len(command) {
			break
		}
		if command[index] == '"' {
			start := index
			index++
			escaped := false
			for index < len(command) {
				if !escaped && command[index] == '"' {
					index++
					break
				}
				if command[index] == '\\' && !escaped {
					escaped = true
				} else {
					escaped = false
				}
				index++
			}
			if index > len(command) || command[index-1] != '"' {
				return nil, errors.New("unterminated quoted argument")
			}
			if index < len(command) && command[index] != ' ' && command[index] != '\t' {
				return nil, errors.New("quoted systemd argument must be followed by whitespace")
			}
			value, err := strconv.Unquote(command[start:index])
			if err != nil {
				return nil, err
			}
			value, err = unescapeSystemdExpansion(value)
			if err != nil {
				return nil, err
			}
			result = append(result, value)
			continue
		}
		start := index
		for index < len(command) && command[index] != ' ' && command[index] != '\t' {
			if strings.ContainsRune("'\\;$|&<>`", rune(command[index])) {
				return nil, errors.New("unsupported systemd command syntax")
			}
			index++
		}
		if start == index {
			return nil, errors.New("empty systemd argument")
		}
		value, err := unescapeSystemdExpansion(command[start:index])
		if err != nil {
			return nil, err
		}
		result = append(result, value)
	}
	return result, nil
}

func unescapeSystemdExpansion(value string) (string, error) {
	var result strings.Builder
	for index := 0; index < len(value); index++ {
		if value[index] != '%' && value[index] != '$' {
			result.WriteByte(value[index])
			continue
		}
		if index+1 >= len(value) || value[index+1] != value[index] {
			return "", errors.New("systemd command uses runtime variable or specifier expansion")
		}
		result.WriteByte(value[index])
		index++
	}
	return result.String(), nil
}

func embeddedPlanFromText(content, prefix string) string {
	for _, line := range strings.Split(content, "\n") {
		line = strings.TrimSpace(line)
		if value, found := strings.CutPrefix(line, prefix); found {
			return strings.TrimSpace(value)
		}
	}
	return ""
}

func (s *Systemd) resolve(reference Reference) Artifact {
	target := s.Target(reference.Connection)
	if reference.UnitName != "" {
		target.UnitName = reference.UnitName
	}
	if reference.ArtifactPath != "" {
		target.Path = reference.ArtifactPath
	}
	return target
}

func (s *Systemd) run(ctx context.Context, args ...string) ([]byte, error) {
	return s.runner.Run(ctx, "systemctl", append([]string{"--user"}, args...), Streams{})
}

func parseProperties(output []byte) map[string]string {
	result := make(map[string]string)
	for _, line := range bytes.Split(output, []byte{'\n'}) {
		key, value, found := bytes.Cut(line, []byte{'='})
		if found {
			result[string(key)] = string(value)
		}
	}
	return result
}

func systemdProcessState(active string) string {
	switch active {
	case "active", "reloading":
		return ProcessRunning
	case "activating":
		return ProcessStarting
	case "failed":
		return ProcessFailed
	case "inactive", "deactivating":
		return ProcessInactive
	default:
		return ProcessUnknown
	}
}

func missingService(output []byte) bool {
	text := strings.ToLower(string(output))
	return strings.Contains(text, "not found") || strings.Contains(text, "not-found") ||
		strings.Contains(text, "does not exist") || strings.Contains(text, "could not find service") ||
		strings.Contains(text, "no such process")
}
