type Systemd struct {
	unitDir string
	runner  CommandRunner
}

func NewSystemd(unitDir string, runner CommandRunner) *Systemd {
	if runner == nil {
		runner = ExecRunner{}
	}
	return &Systemd{unitDir: unitDir, runner: runner}
}

func (s *Systemd) Name() string { return "systemd" }

func (s *Systemd) Capabilities() Capabilities {
	return Capabilities{Registration: true, Background: true, Persistence: true, Logs: true, Discovery: true, UserScope: true}
}

func (s *Systemd) Target(connection string) Artifact {
	unit := "tunlite-" + connection + ".service"
	return Artifact{Connection: connection, Adapter: s.Name(), UnitName: unit, Path: filepath.Join(s.unitDir, unit)}
}

func (s *Systemd) Build(connection string, executionPlan plan.ExecutionPlan) (Artifact, error) {
	return s.build(s.Target(connection), connection, executionPlan)
}

func (s *Systemd) BuildBound(reference Reference, executionPlan plan.ExecutionPlan) (Artifact, error) {
	target := s.resolve(reference)
	return s.build(target, reference.Connection, executionPlan)
}

func (s *Systemd) build(artifact Artifact, connection string, executionPlan plan.ExecutionPlan) (Artifact, error) {
	if err := plan.Validate(executionPlan); err != nil {
		return Artifact{}, err
	}
	digest, err := PlanDigest(executionPlan)
	if err != nil {
		return Artifact{}, err
	}
	artifact.Plan = executionPlan
	artifact.PlanDigest = digest
	embedded, err := encodeEmbeddedPlan(executionPlan)
	if err != nil {
		return Artifact{}, err
	}
	artifact.Content = renderSystemd(connection, digest, embedded, executionPlan)
	return artifact, nil
}

func renderSystemd(connection, digest, embedded string, executionPlan plan.ExecutionPlan) []byte {
	var output strings.Builder
	fmt.Fprintln(&output, "# Generated by Tunlite. DO NOT EDIT.")
	fmt.Fprintf(&output, "# Connection: %s\n# Plan-SHA256: %s\n", connection, digest)
	fmt.Fprintf(&output, "# %s%s\n", embeddedPlanPrefix, embedded)
	fmt.Fprintln(&output, "[Unit]")
	fmt.Fprintf(&output, "Description=Tunlite connection %s\n", connection)
	fmt.Fprintln(&output, "Wants=network-online.target")
	fmt.Fprintln(&output, "After=network-online.target")
	fmt.Fprintln(&output, "")
	fmt.Fprintln(&output, "[Service]")
	fmt.Fprintln(&output, "Type=simple")
	arguments := append([]string{executionPlan.Exec.Program}, executionPlan.Exec.Args...)
	fmt.Fprintf(&output, "ExecStart=%s\n", quoteSystemdArguments(arguments))
	if executionPlan.Exec.WorkingDirectory != nil {
		fmt.Fprintf(&output, "WorkingDirectory=%s\n", quoteSystemd(*executionPlan.Exec.WorkingDirectory))
	}
	keys := make([]string, 0, len(executionPlan.Exec.Environment))
	for key := range executionPlan.Exec.Environment {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		fmt.Fprintf(&output, "Environment=%s\n", quoteSystemd(key+"="+executionPlan.Exec.Environment[key]))
	}
	restart := executionPlan.Lifecycle.Restart
	if restart == "never" {
		restart = "no"
	}
	fmt.Fprintf(&output, "Restart=%s\n", restart)
	fmt.Fprintf(&output, "RestartSec=%ds\n", executionPlan.Lifecycle.RestartDelaySeconds)
	fmt.Fprintf(&output, "TimeoutStopSec=%ds\n", executionPlan.Lifecycle.StopTimeoutSeconds)
	fmt.Fprintln(&output, "KillMode=control-group")
	fmt.Fprintln(&output, "")
	fmt.Fprintln(&output, "[Install]")
	fmt.Fprintln(&output, "WantedBy=default.target")
	return []byte(output.String())
}

func quoteSystemdArguments(arguments []string) string {
	quoted := make([]string, len(arguments))
	for index, argument := range arguments {
		quoted[index] = quoteSystemd(argument)
	}
	return strings.Join(quoted, " ")
}

func quoteSystemd(value string) string {
	value = strings.ReplaceAll(value, "%", "%%")
	value = strings.ReplaceAll(value, "$", "$$")
	return strconv.QuoteToASCII(value)
}

func (s *Systemd) Materialize(ctx context.Context, artifact Artifact) error {
	previous, existed, err := installArtifact(artifact.Path, artifact.Content)
	if err != nil {
		return fmt.Errorf("install systemd unit: %w", err)
	}
	rollback := func(cause error) error {
		var failures []error
		if err := restoreArtifact(artifact.Path, previous, existed); err != nil {
			failures = append(failures, err)
		}
		if _, err := s.run(ctx, "daemon-reload"); err != nil {
			failures = append(failures, err)
		}
		return errors.Join(append([]error{cause}, failures...)...)
	}
	if _, err := s.run(ctx, "daemon-reload"); err != nil {
		return rollback(err)
	}
	return nil
}

func (s *Systemd) Remove(ctx context.Context, reference Reference) error {
	target := s.resolve(reference)
	output, err := s.run(ctx, "disable", "--now", target.UnitName)
	if err != nil && !missingService(output) {
		return err
	}
	if err := os.Remove(target.Path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	_, err = s.run(ctx, "daemon-reload")
	return err
}

