package service

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/yuanyuanzijin/tunlite/internal/plan"
)

type Systemd struct {
	unitDir string
	runner  CommandRunner
}

func NewSystemd(unitDir string, runner CommandRunner) *Systemd {
	if runner == nil {
		runner = ExecRunner{}
	}
	return &Systemd{unitDir: unitDir, runner: runner}
}

func (s *Systemd) Name() string { return "systemd" }

func (s *Systemd) Target(connection string) Artifact {
	unit := "tunlite-" + connection + ".service"
	return Artifact{Connection: connection, Adapter: s.Name(), UnitName: unit, Path: filepath.Join(s.unitDir, unit)}
}

func (s *Systemd) Build(connection string, executionPlan plan.ExecutionPlan) (Artifact, error) {
	if err := plan.Validate(executionPlan); err != nil {
		return Artifact{}, err
	}
	digest, err := PlanDigest(executionPlan)
	if err != nil {
		return Artifact{}, err
	}
	artifact := s.Target(connection)
	artifact.Plan = executionPlan
	artifact.PlanDigest = digest
	artifact.Content = renderSystemd(connection, digest, executionPlan)
	return artifact, nil
}

func renderSystemd(connection, digest string, executionPlan plan.ExecutionPlan) []byte {
	var output strings.Builder
	fmt.Fprintln(&output, "# Generated by Tunlite. DO NOT EDIT.")
	fmt.Fprintf(&output, "# Connection: %s\n# Plan-SHA256: %s\n", connection, digest)
	fmt.Fprintln(&output, "[Unit]")
	fmt.Fprintf(&output, "Description=Tunlite connection %s\n", connection)
	fmt.Fprintln(&output, "Wants=network-online.target")
	fmt.Fprintln(&output, "After=network-online.target")
	fmt.Fprintln(&output, "")
	fmt.Fprintln(&output, "[Service]")
	fmt.Fprintln(&output, "Type=simple")
	arguments := append([]string{executionPlan.Exec.Program}, executionPlan.Exec.Args...)
	fmt.Fprintf(&output, "ExecStart=%s\n", quoteSystemdArguments(arguments))
	if executionPlan.Exec.WorkingDirectory != nil {
		fmt.Fprintf(&output, "WorkingDirectory=%s\n", quoteSystemd(*executionPlan.Exec.WorkingDirectory))
	}
	keys := make([]string, 0, len(executionPlan.Exec.Environment))
	for key := range executionPlan.Exec.Environment {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		fmt.Fprintf(&output, "Environment=%s\n", quoteSystemd(key+"="+executionPlan.Exec.Environment[key]))
	}
	restart := executionPlan.Lifecycle.Restart
	if restart == "never" {
		restart = "no"
	}
	fmt.Fprintf(&output, "Restart=%s\n", restart)
	fmt.Fprintf(&output, "RestartSec=%ds\n", executionPlan.Lifecycle.RestartDelaySeconds)
	fmt.Fprintf(&output, "TimeoutStopSec=%ds\n", executionPlan.Lifecycle.StopTimeoutSeconds)
	fmt.Fprintln(&output, "KillMode=control-group")
	fmt.Fprintln(&output, "")
	fmt.Fprintln(&output, "[Install]")
	fmt.Fprintln(&output, "WantedBy=default.target")
	return []byte(output.String())
}

func quoteSystemdArguments(arguments []string) string {
	quoted := make([]string, len(arguments))
	for index, argument := range arguments {
		quoted[index] = quoteSystemd(argument)
	}
	return strings.Join(quoted, " ")
}

func quoteSystemd(value string) string {
	value = strings.ReplaceAll(value, "%", "%%")
	value = strings.ReplaceAll(value, "$", "$$")
	return strconv.QuoteToASCII(value)
}

func (s *Systemd) Enable(ctx context.Context, artifact Artifact) error {
	previous, existed, err := installArtifact(artifact.Path, artifact.Content)
	if err != nil {
		return fmt.Errorf("install systemd unit: %w", err)
	}
	rollback := func(cause error) error {
		var failures []error
		if err := restoreArtifact(artifact.Path, previous, existed); err != nil {
			failures = append(failures, err)
		}
		if _, err := s.run(ctx, "daemon-reload"); err != nil {
			failures = append(failures, err)
		}
		if existed {
			if _, err := s.run(ctx, "restart", artifact.UnitName); err != nil {
				failures = append(failures, err)
			}
		} else {
			_, _ = s.run(ctx, "disable", "--now", artifact.UnitName)
		}
		return errors.Join(append([]error{cause}, failures...)...)
	}
	if _, err := s.run(ctx, "daemon-reload"); err != nil {
		return rollback(err)
	}
	if _, err := s.run(ctx, "enable", artifact.UnitName); err != nil {
		return rollback(err)
	}
	if _, err := s.run(ctx, "restart", artifact.UnitName); err != nil {
		return rollback(err)
	}
	return nil
}

func (s *Systemd) Disable(ctx context.Context, connection string) error {
	target := s.Target(connection)
	output, err := s.run(ctx, "disable", "--now", target.UnitName)
	if err != nil && !missingService(output) {
		return err
	}
	if err := os.Remove(target.Path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	_, err = s.run(ctx, "daemon-reload")
	return err
}

func (s *Systemd) Restart(ctx context.Context, connection string) error {
	_, err := s.run(ctx, "restart", s.Target(connection).UnitName)
	return err
}

func (s *Systemd) Inspect(ctx context.Context, connection string) (Observation, error) {
	target := s.Target(connection)
	observation := Observation{ProcessState: ProcessUnknown, Platform: map[string]any{"unit": target.UnitName}}
	artifact, err := os.ReadFile(target.Path)
	if err == nil {
		observation.Installed = true
		observation.Artifact = artifact
	} else if !errors.Is(err, os.ErrNotExist) {
		return observation, err
	}
	enabledOutput, enabledErr := s.run(ctx, "is-enabled", target.UnitName)
	enabledText := strings.TrimSpace(string(enabledOutput))
	observation.Enabled = enabledText == "enabled" || enabledText == "enabled-runtime"
	if enabledErr != nil && !missingService(enabledOutput) && enabledText != "disabled" {
		return observation, enabledErr
	}
	showOutput, showErr := s.run(ctx, "show", target.UnitName, "--property=LoadState", "--property=ActiveState", "--property=SubState", "--property=Result", "--no-pager")
	if showErr != nil {
		if missingService(showOutput) && !observation.Installed {
			observation.ProcessState = ProcessInactive
			return observation, nil
		}
		return observation, showErr
	}
	properties := parseProperties(showOutput)
	observation.Platform["loadState"] = properties["LoadState"]
	observation.Platform["activeState"] = properties["ActiveState"]
	observation.Platform["subState"] = properties["SubState"]
	observation.Platform["result"] = properties["Result"]
	observation.ProcessState = systemdProcessState(properties["ActiveState"])
	return observation, nil
}

func (s *Systemd) Logs(ctx context.Context, connection string, lines int, follow bool, streams Streams) error {
	args := []string{"--user", "-u", s.Target(connection).UnitName, "-n", strconv.Itoa(lines), "--no-pager"}
	if follow {
		args = append(args, "--follow")
	}
	_, err := s.runner.Run(ctx, "journalctl", args, streams)
	return err
}

func (s *Systemd) run(ctx context.Context, args ...string) ([]byte, error) {
	return s.runner.Run(ctx, "systemctl", append([]string{"--user"}, args...), Streams{})
}

func parseProperties(output []byte) map[string]string {
	result := make(map[string]string)
	for _, line := range bytes.Split(output, []byte{'\n'}) {
		key, value, found := bytes.Cut(line, []byte{'='})
		if found {
			result[string(key)] = string(value)
		}
	}
	return result
}

func systemdProcessState(active string) string {
	switch active {
	case "active", "reloading":
		return ProcessRunning
	case "activating":
		return ProcessStarting
	case "failed":
		return ProcessFailed
	case "inactive", "deactivating":
		return ProcessInactive
	default:
		return ProcessUnknown
	}
}

func missingService(output []byte) bool {
	text := strings.ToLower(string(output))
	return strings.Contains(text, "not found") || strings.Contains(text, "not-found") ||
		strings.Contains(text, "does not exist") || strings.Contains(text, "could not find service") ||
		strings.Contains(text, "no such process")
}
